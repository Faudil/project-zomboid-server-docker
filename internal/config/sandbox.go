package config

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func (c *ServerConfig) WriteSandboxVars() error {
	dir := filepath.Dir(c.SandboxVarsPath())
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("creating sandbox vars directory: %w", err)
	}

	// Defaults mirror the game's b42 "Apocalypse" preset
	// (server-files/media/lua/shared/Sandbox/Apocalypse.lua).
	vars := map[string]string{
		"Zombies":             "4",
		"Distribution":        "1",
		"DayLength":           "4",
		"StartYear":           "1",
		"StartMonth":          "7",
		"StartDay":            "9",
		"StartTime":           "2",
		"WaterShutModifier":   "14",
		"ElecShutModifier":    "14",
		"WaterShut":           "2",
		"ElecShut":            "2",
		"FoodLootNew":         "0.8",
		"WeaponLootNew":       "0.6",
		"OtherLootNew":        "0.8",
		"Temperature":         "3",
		"Rain":                "3",
		"ErosionSpeed":        "4",
		"ErosionDays":         "0",
		"Farming":             "3",
		"CompostTime":         "2",
		"StatsDecrease":       "3",
		"NatureAbundance":     "3",
		"Alarm":               "4",
		"LockedHouses":        "6",
		"GeneratorSpawning":   "4",
		"SurvivorHouseChance": "3",
		"VehicleStoryChance":  "3",
		"ZoneStoryChance":     "3",
		"AnnotatedMapChance":  "4",
		"TimeSinceApo":        "1",
		"NightDarkness":       "3",
		"Helicopter":          "2",
		"MetaEvent":           "2",
		"SleepingEvent":       "1",
		"ZombieLore":          zombieLoreBlock(nil),
	}

	// SANDBOX_MODE applies gameplay/performance presets on top of the base
	// Apocalypse values. SANDBOX_* env overrides below always win over them.
	for k, v := range sandboxModeOverrides(c.SandboxMode) {
		vars[k] = v
	}

	// SANDBOX_* env overrides may use Build 41 sandbox names, which b42
	// silently drops. Map the known renames to their b42 equivalents so
	// overrides keep working.
	legacyAliases := map[string]string{
		"FoodLoot":       "FoodLootNew",
		"WeaponLoot":     "WeaponLootNew",
		"OtherLoot":      "OtherLootNew",
		"SurvivorHouses": "SurvivorHouseChance",
		"MonthsSinceApo": "TimeSinceApo",
		"DarknessNight":  "NightDarkness",
	}

	// SANDBOX_MODE applies gameplay/performance presets on top of the base
	// Apocalypse values. SANDBOX_* env overrides below always win over them.
	for k, v := range sandboxModeOverrides(c.SandboxMode) {
		vars[k] = v
	}

	nested := map[string]map[string]string{}
	for k, v := range c.SandboxVars {
		if alias, ok := legacyAliases[k]; ok {
			fmt.Printf("WARNING: SANDBOX_%s was renamed in b42, applying it to %s\n", k, alias)
			vars[alias] = v
			continue
		}
		// Nested keys use dot notation: SANDBOX_ZombieConfig.PopulationMultiplier=0.5
		// writes into the ZombieConfig = { ... } table.
		section, sub, ok := strings.Cut(k, ".")
		if ok {
			switch section {
			case "ZombieConfig", "ZombieLore":
				if nested[section] == nil {
					nested[section] = map[string]string{}
				}
				nested[section][sub] = v
			default:
				fmt.Printf("WARNING: SANDBOX_%s: %q is not a supported nested sandbox table, ignoring\n", k, section)
			}
			continue
		}
		vars[k] = v
	}

	// Render the nested tables last so SANDBOX_MODE presets and SANDBOX_*
	// overrides both land in the final blocks (env overrides win).
	vars["ZombieConfig"] = zombieConfigBlock(c.SandboxMode, nested["ZombieConfig"])
	vars["ZombieLore"] = zombieLoreBlock(nested["ZombieLore"])

	var sb strings.Builder
	sb.WriteString("-- Generated by project-zomboid-server-docker\n")
	sb.WriteString("SandboxVars = {\n")

	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for i, k := range keys {
		sep := ","
		if i == len(keys)-1 {
			sep = ""
		}
		v := vars[k]
		sb.WriteString(fmt.Sprintf("    %s = %s%s\n", k, v, sep))
	}

	sb.WriteString("}\n")

	return os.WriteFile(c.SandboxVarsPath(), []byte(sb.String()), 0644)
}

// sandboxModes are the accepted SANDBOX_MODE values, used for validation.
var sandboxModes = map[string]bool{
	"apocalypse":  true,
	"performance": true,
	"max":         true,
}

// sandboxModeOverrides returns the extra sandbox options a SANDBOX_MODE
// applies over the b42 Apocalypse base. Empty for the default mode.
func sandboxModeOverrides(mode string) map[string]string {
	switch mode {
	case "performance", "max":
		// World-cleanup knobs with near-zero gameplay impact. Corpses,
		// blood splats and rotten food pile up on long-running servers
		// and are well-known lag sources; the Apocalypse defaults never
		// remove them (or wait 9 days for corpses).
		return map[string]string{
			"HoursForCorpseRemoval":    "48",
			"BloodSplatLifespanDays":   "7",
			"DaysForRottenFoodRemoval": "14",
			"MaximumRatIndex":          "0",
			"HoursForWorldItemRemoval": "12",
		}
	default:
		return nil
	}
}

// zombieConfigBlock renders the b42 ZombieConfig table for the given
// SANDBOX_MODE plus any SANDBOX_ZombieConfig.* env overrides. The "max" mode
// cuts population pressure, which is the dominant factor for server TPS on
// long-running worlds.
func zombieConfigBlock(mode string, overrides map[string]string) string {
	zc := map[string]string{
		"PopulationMultiplier":      "0.65",
		"PopulationStartMultiplier": "1.0",
		"PopulationPeakMultiplier":  "1.5",
		"PopulationPeakDay":         "28",
		"RespawnHours":              "0.0",
		"RespawnUnseenHours":        "0.0",
		"RespawnMultiplier":         "0.0",
		"RedistributeHours":         "12.0",
		"FollowSoundDistance":       "100",
		"RallyGroupSize":            "20",
		"RallyGroupSizeVariance":    "50",
		"RallyTravelDistance":       "20",
		"RallyGroupSeparation":      "15",
		"RallyGroupRadius":          "3",
		"ZombiesCountBeforeDelete":  "300",
	}
	if mode == "max" {
		zc["PopulationMultiplier"] = "0.35"
		zc["PopulationStartMultiplier"] = "0.5"
		zc["PopulationPeakMultiplier"] = "1.0"
		zc["RedistributeHours"] = "24.0"
		zc["FollowSoundDistance"] = "50"
		zc["RallyGroupSize"] = "10"
		zc["RallyGroupSizeVariance"] = "25"
	}
	applyOverrides(zc, overrides)
	return renderBlock(zc)
}

