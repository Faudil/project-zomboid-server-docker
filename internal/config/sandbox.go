func applyOverrides(base, overrides map[string]string) {
	for k, v := range overrides {
		base[k] = v
	}
}

func renderBlock(entries map[string]string) string {
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var sb strings.Builder
	sb.WriteString("{\n")
	for i, k := range keys {
		sep := ","
		if i == len(keys)-1 {
			sep = ""
		}
		sb.WriteString(fmt.Sprintf("            %s = %s%s\n", k, entries[k], sep))
	}
	sb.WriteString("        }")
	return sb.String()
}
